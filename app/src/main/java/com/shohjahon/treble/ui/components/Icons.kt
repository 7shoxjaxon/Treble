@Composable
fun TrebleIcon(path: String, tint: Color, modifier: Modifier = Modifier, size: Dp = 22.dp) {
    val parsed = remember(path) { PathParser().parsePathString(path).toPath() }
    Canvas(modifier = modifier.size(size)) {
        withTransform({
            scale(scaleX = this.size.width / 24f, scaleY = this.size.height / 24f, pivot = Offset.Zero)
        }) {
            drawPath(path = parsed, color = tint)
        }
    }
}

/** Futbol to'pi ikonkasi (aylana + markazdagi beshburchak). */
@Composable
fun BallIcon(tint: Color, modifier: Modifier = Modifier, size: Dp = 22.dp) {
    Canvas(modifier = modifier.size(size)) {
        val w = this.size.width
        val c = Offset(w / 2f, w / 2f)
        drawCircle(color = tint, radius = w * 0.42f, center = c, style = Stroke(width = w * 0.09f))
        val r = w * 0.17f
        val pentagon = androidx.compose.ui.graphics.Path()
        for (i in 0 until 5) {
            val angle = Math.toRadians((-90 + i * 72).toDouble())
            val x = c.x + (r * Math.cos(angle)).toFloat()
            val y = c.y + (r * Math.sin(angle)).toFloat()
            if (i == 0) pentagon.moveTo(x, y) else pentagon.lineTo(x, y)
        }
        pentagon.close()
        drawPath(pentagon, color = tint)
        // markazdan chetga qisqa chiziqlar
        for (i in 0 until 5) {
            val angle = Math.toRadians((-90 + i * 72).toDouble())
            val from = Offset(c.x + (r * 1.2f * Math.cos(angle)).toFloat(), c.y + (r * 1.2f * Math.sin(angle)).toFloat())
            val to = Offset(c.x + (w * 0.40f * Math.cos(angle)).toFloat(), c.y + (w * 0.40f * Math.sin(angle)).toFloat())
            drawLine(color = tint, start = from, end = to, strokeWidth = w * 0.06f)
        }
    }
}
